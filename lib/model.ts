// Token Radar — the value model and farm plans for token-radar-01.
//
// The board ranks protocols that record no token, by an implied value that is
// derived only from the snapshot's own figures: TVL, seven-day TVL change,
// how long the protocol has been tracked with no token, and how many chains
// its TVL spans. No protocol name is ever special-cased.
//
//   implied = tvl_usd x 0.30                       (base: a token at 30% of TVL)
//           x growthMult                           (7-day change, clamped)
//           x maturityMult                         (older with no token: steadier)
//           x breadthMult                          (more chains: wider moat)
//
// A protocol whose token already trades is never ranked: the dashboard shows
// it apart, at the market's own capitalisation, never at a modelled value.

// ------------------------------------------------------------------ types

export interface SnapshotProtocol {
  slug: string;
  name: string;
  category: string | null;
  chains: string[];
  tvl_usd: number;
  change_7d: number | null;
  mcap_usd: number | null;
  listed_at: string | null;
  gecko_id: string | null;
  symbol: string | null;
}

export interface Snapshot {
  as_of: string;
  source: string;
  floor_usd: number;
  protocols: SnapshotProtocol[];
  watchlist: string[];
}

export interface ModelConstants {
  base_multiple: number;
  growth_weight: number;
  growth_floor: number;
  growth_cap: number;
  maturity_floor: number;
  maturity_range: number;
  maturity_days: number;
  unknown_age_days: number;
  breadth_per_chain: number;
  breadth_max: number;
}

export const MODEL: ModelConstants = {
  base_multiple: 0.3,
  growth_weight: 0.6,
  growth_floor: -50,
  growth_cap: 100,
  maturity_floor: 0.75,
  maturity_range: 0.25,
  maturity_days: 1460,
  unknown_age_days: 180,
  breadth_per_chain: 0.05,
  breadth_max: 1.3,
};

export const MODEL_VERSION = 'radar-2';

/** How many pre-token protocols below the watchlist floor the board carries. */
export const EARLY_ROWS = 260;
/** How many live-token protocols the dashboard's Live view carries. */
export const LIVE_ROWS = 24;

export interface FarmStep {
  text: string;
  cost: string;
  time: string;
}

